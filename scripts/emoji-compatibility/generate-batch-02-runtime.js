#!/usr/bin/env node

const fs = require('node:fs')
const path = require('node:path')

const { validateManifest } = require('./validate-batch-02-manifest')

const ROOT = path.resolve(__dirname, '../..')
const MANIFEST_PATH = path.join(__dirname, 'batch-02-manifest.json')
const DEVICE_RESULTS_PATH = path.join(__dirname, 'device-results-2026-07-18.json')
const OUTPUT_PATH = path.join(ROOT, 'miniprogram/pages/icon-compatibility/emoji-candidates-batch-02.js')
const APPROVED_OUTPUT_PATH = path.join(ROOT, 'miniprogram/utils/ui-symbols-batch-02.js')

function generateRuntimeSource(manifest) {
  validateManifest(manifest)
  const itemsByCategory = new Map(manifest.categories.map(category => [category.id, []]))
  manifest.items.forEach(item => {
    itemsByCategory.get(item.categoryId).push([
      item.glyph,
      item.label,
      item.sequence,
      item.emojiVersion
    ])
  })

  const categoryTuples = manifest.categories.map(category => [
    category.id,
    category.name,
    category.count,
    category.riskNote,
    itemsByCategory.get(category.id)
  ])

  return `// Generated by scripts/emoji-compatibility/generate-batch-02-runtime.js. Do not edit.\n` +
`function deepFreeze(value) {\n` +
`  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value\n` +
`  Object.values(value).forEach(deepFreeze)\n` +
`  return Object.freeze(value)\n` +
`}\n\n` +
`function unicodeSequence(glyph) {\n` +
`  return [...String(glyph || '')]\n` +
`    .map(char => \`U+\${char.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')}\`)\n` +
`    .join(' ')\n` +
`}\n\n` +
`const CATEGORY_TUPLES = ${JSON.stringify(categoryTuples)}\n\n` +
`const EMOJI_BATCH_02 = deepFreeze({\n` +
`  id: ${JSON.stringify(manifest.id)},\n` +
`  count: ${manifest.count},\n` +
`  categories: CATEGORY_TUPLES.map(([id, name, count, riskNote, items]) => ({\n` +
`    id,\n` +
`    name,\n` +
`    count,\n` +
`    riskNote,\n` +
`    items: items.map(([glyph, label, sequence, emojiVersion], index) => ({\n` +
`      id: \`\${id}-\${String(index + 1).padStart(3, '0')}\`,\n` +
`      order: index + 1,\n` +
`      glyph,\n` +
`      label,\n` +
`      sequence,\n` +
`      emojiVersion\n` +
`    }))\n` +
`  }))\n` +
`})\n\n` +
`const EMOJI_BATCH_02_COUNT = EMOJI_BATCH_02.count\n\n` +
`function findBatch02Category(categoryId) {\n` +
`  return EMOJI_BATCH_02.categories.find(category => category.id === categoryId) || null\n` +
`}\n\n` +
`module.exports = {\n` +
`  EMOJI_BATCH_02,\n` +
`  EMOJI_BATCH_02_COUNT,\n` +
`  findBatch02Category,\n` +
`  unicodeSequence\n` +
`}\n`
}

function generateApprovedSource(manifest, results) {
  validateManifest(manifest)
  if (results.batchId !== manifest.id || results.candidateCount !== manifest.count) {
    throw new Error('device results do not match the batch-02 manifest')
  }

  const failedIds = new Set(results.failedIds)
  const approvedCount = manifest.items.filter(item => !failedIds.has(item.id)).length
  if (approvedCount !== results.approvedCount) {
    throw new Error(`approved count mismatch: expected ${results.approvedCount}, got ${approvedCount}`)
  }

  const categoryCounts = manifest.categories.map(category => category.count)
  const glyphs = manifest.items.map(item => failedIds.has(item.id) ? null : item.glyph)

  return `// Generated by scripts/emoji-compatibility/generate-batch-02-runtime.js. Do not edit.\n` +
`// Android + iOS device-verified production whitelist (${results.testedAt}).\n` +
`const CATEGORY_COUNTS = ${JSON.stringify(categoryCounts)}\n` +
`const GLYPHS = ${JSON.stringify(glyphs)}\n` +
`const REJECTED_BATCH_02_IDS = Object.freeze(${JSON.stringify(results.failedIds)})\n\n` +
`const VERIFIED_BATCH_02_SYMBOLS = {}\n` +
`let offset = 0\n` +
`CATEGORY_COUNTS.forEach((count, categoryIndex) => {\n` +
`  const categoryId = \`B02-C\${String(categoryIndex + 1).padStart(2, '0')}\`\n` +
`  for (let order = 1; order <= count; order += 1) {\n` +
`    const glyph = GLYPHS[offset]\n` +
`    if (glyph) VERIFIED_BATCH_02_SYMBOLS[\`\${categoryId}-\${String(order).padStart(3, '0')}\`] = glyph\n` +
`    offset += 1\n` +
`  }\n` +
`})\n` +
`Object.freeze(VERIFIED_BATCH_02_SYMBOLS)\n\n` +
`module.exports = {\n` +
`  VERIFIED_BATCH_02_SYMBOLS,\n` +
`  REJECTED_BATCH_02_IDS\n` +
`}\n`
}

function readManifest() {
  return JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'))
}

function readDeviceResults() {
  return JSON.parse(fs.readFileSync(DEVICE_RESULTS_PATH, 'utf8'))
}

function writeGeneratedFile(outputPath, source) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true })
  const temporary = `${outputPath}.tmp-${process.pid}`
  try {
    fs.writeFileSync(temporary, source)
    fs.renameSync(temporary, outputPath)
  } finally {
    if (fs.existsSync(temporary)) fs.unlinkSync(temporary)
  }
}

function main(args = process.argv.slice(2)) {
  const mode = args[0]
  if (mode !== '--write' && mode !== '--verify') {
    throw new Error('usage: generate-batch-02-runtime.js --write|--verify')
  }
  const manifest = readManifest()
  const outputs = [
    [OUTPUT_PATH, generateRuntimeSource(manifest)],
    [APPROVED_OUTPUT_PATH, generateApprovedSource(manifest, readDeviceResults())]
  ]
  if (mode === '--write') {
    outputs.forEach(([outputPath, source]) => {
      writeGeneratedFile(outputPath, source)
      console.log(`Wrote ${outputPath}`)
    })
    return
  }
  outputs.forEach(([outputPath, source]) => {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== source) {
      throw new Error(`generated runtime is stale: ${outputPath}`)
    }
    console.log(`Runtime is current: ${outputPath}`)
  })
}

module.exports = { generateRuntimeSource, generateApprovedSource, main }

if (require.main === module) {
  try {
    main()
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
