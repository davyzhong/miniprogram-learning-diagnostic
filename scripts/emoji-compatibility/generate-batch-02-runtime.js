#!/usr/bin/env node

const fs = require('node:fs')
const path = require('node:path')

const { validateManifest } = require('./validate-batch-02-manifest')

const ROOT = path.resolve(__dirname, '../..')
const MANIFEST_PATH = path.join(__dirname, 'batch-02-manifest.json')
const OUTPUT_PATH = path.join(ROOT, 'miniprogram/pages/icon-compatibility/emoji-candidates-batch-02.js')

function generateRuntimeSource(manifest) {
  validateManifest(manifest)
  const itemsByCategory = new Map(manifest.categories.map(category => [category.id, []]))
  manifest.items.forEach(item => {
    itemsByCategory.get(item.categoryId).push([
      item.glyph,
      item.label,
      item.sequence,
      item.emojiVersion
    ])
  })

  const categoryTuples = manifest.categories.map(category => [
    category.id,
    category.name,
    category.count,
    category.riskNote,
    itemsByCategory.get(category.id)
  ])

  return `// Generated by scripts/emoji-compatibility/generate-batch-02-runtime.js. Do not edit.\n` +
`function deepFreeze(value) {\n` +
`  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value\n` +
`  Object.values(value).forEach(deepFreeze)\n` +
`  return Object.freeze(value)\n` +
`}\n\n` +
`function unicodeSequence(glyph) {\n` +
`  return [...String(glyph || '')]\n` +
`    .map(char => \`U+\${char.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')}\`)\n` +
`    .join(' ')\n` +
`}\n\n` +
`const CATEGORY_TUPLES = ${JSON.stringify(categoryTuples)}\n\n` +
`const EMOJI_BATCH_02 = deepFreeze({\n` +
`  id: ${JSON.stringify(manifest.id)},\n` +
`  count: ${manifest.count},\n` +
`  categories: CATEGORY_TUPLES.map(([id, name, count, riskNote, items]) => ({\n` +
`    id,\n` +
`    name,\n` +
`    count,\n` +
`    riskNote,\n` +
`    items: items.map(([glyph, label, sequence, emojiVersion], index) => ({\n` +
`      id: \`\${id}-\${String(index + 1).padStart(3, '0')}\`,\n` +
`      order: index + 1,\n` +
`      glyph,\n` +
`      label,\n` +
`      sequence,\n` +
`      emojiVersion\n` +
`    }))\n` +
`  }))\n` +
`})\n\n` +
`const EMOJI_BATCH_02_COUNT = EMOJI_BATCH_02.count\n\n` +
`function findBatch02Category(categoryId) {\n` +
`  return EMOJI_BATCH_02.categories.find(category => category.id === categoryId) || null\n` +
`}\n\n` +
`module.exports = {\n` +
`  EMOJI_BATCH_02,\n` +
`  EMOJI_BATCH_02_COUNT,\n` +
`  findBatch02Category,\n` +
`  unicodeSequence\n` +
`}\n`
}

function readManifest() {
  return JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'))
}

function writeRuntime(source) {
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true })
  const temporary = `${OUTPUT_PATH}.tmp-${process.pid}`
  try {
    fs.writeFileSync(temporary, source)
    fs.renameSync(temporary, OUTPUT_PATH)
  } finally {
    if (fs.existsSync(temporary)) fs.unlinkSync(temporary)
  }
}

function main(args = process.argv.slice(2)) {
  const mode = args[0]
  if (mode !== '--write' && mode !== '--verify') {
    throw new Error('usage: generate-batch-02-runtime.js --write|--verify')
  }
  const source = generateRuntimeSource(readManifest())
  if (mode === '--write') {
    writeRuntime(source)
    console.log(`Wrote ${OUTPUT_PATH}`)
    return
  }
  if (!fs.existsSync(OUTPUT_PATH) || fs.readFileSync(OUTPUT_PATH, 'utf8') !== source) {
    throw new Error(`generated runtime is stale: ${OUTPUT_PATH}`)
  }
  console.log(`Runtime is current: ${OUTPUT_PATH}`)
}

module.exports = { generateRuntimeSource, main }

if (require.main === module) {
  try {
    main()
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
