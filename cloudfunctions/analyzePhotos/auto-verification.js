/**
 * 验证卷自动生成引擎
 *
 * 诊断报告完成后，如果有 pendingBottlenecks，自动触发验证卷生成。
 * 用户无需手动点击"生成验证卷"，只需预览/打印/上传作答。
 *
 * 设计文档：docs/subject-design/验证卷自动生成设计文档.md
 */

const MAX_RETRY_ATTEMPTS = 3;
const RETRY_DELAY_MS = 10000; // 10秒后重试

/**
 * 从 profile 提取待验证的卡点代码列表
 */
function extractPendingTargets(profile) {
  const pending = (profile && profile.pendingBottlenecks) || [];
  const targets = [];
  const seen = new Set();
  for (const item of pending) {
    const code = item.lpCode || item.bottleneckId || item.id;
    if (code && !seen.has(code)) {
      seen.add(code);
      targets.push(code);
    }
    // 细卡点候选也加入
    for (const cand of item.candidateBottlenecks || []) {
      const candCode = cand.bottleneckId || cand.id;
      if (candCode && !seen.has(candCode)) {
        seen.add(candCode);
        targets.push(candCode);
      }
    }
  }
  // 限制在 VERIFICATION_TASK_PACK_TARGET_LIMIT 内
  return targets.slice(0, 8);
}

/**
 * 覆盖旧卷：标记同学科未验证的旧验证卷为 superseded
 */
async function supersedeOldPapers(db, studentId, subject, newReportId) {
  const oldPapers = await db.collection('papers')
    .where({
      studentId,
      subject,
      type: 'verification',
    })
    .limit(20)
    .get();

  let superseded = 0;
  for (const old of oldPapers.data || []) {
    // 跳过已 superseded 的
    if (old.generationStatus === 'superseded') continue;
    // 只覆盖没有验证报告的旧卷（即用户还没上传作答的）
    const verifReports = await db.collection('reports')
      .where({ studentId, subject, type: 'verification', paperId: old._id })
      .limit(1)
      .get();
    if ((verifReports.data || []).length === 0) {
      await db.collection('papers').doc(old._id).update({
        data: {
          generationStatus: 'superseded',
          supersededAt: new Date(),
          supersededBy: newReportId,
        },
      });
      superseded += 1;
    }
  }
  return superseded;
}

/**
 * 创建 generating 状态的 paper 记录
 */
async function createGeneratingPaper(db, { studentId, subject, targets, reportId, openId }) {
  const now = new Date();
  const res = await db.collection('papers').add({
    data: {
      _openid: openId,
      studentId,
      subject,
      type: 'verification',
      bottleneckTargets: targets,
      questions: [],
      generationStatus: 'generating',
      autoGenerated: true,
      generationAttempts: 0,
      generationError: '',
      triggeredByReport: reportId,
      createdAt: now,
      generatedAt: now,
    },
  });
  return res._id;
}

/**
 * 调用 generatePaper 云函数生成试卷内容，更新 paper 记录
 */
async function invokeGeneratePaper(cloud, { paperId, studentId, subject, targets }) {
  const res = await cloud.callFunction({
    name: 'generatePaper',
    data: {
      studentId,
      subject,
      type: 'verification',
      targets,
      _autoPaperId: paperId, // 告诉 generatePaper 更新这条记录而非新建
    },
  });
  const result = res.result || {};
  if (!result.success) {
    throw new Error(result.error || 'generatePaper 返回失败');
  }
  return result;
}

/**
 * 带重试的生成
 */
async function generateWithRetry(db, cloud, { paperId, studentId, subject, targets, attempt = 0 }) {
  try {
    const result = await invokeGeneratePaper(cloud, { paperId, studentId, subject, targets });
    await db.collection('papers').doc(paperId).update({
      data: {
        generationStatus: 'ready',
        generationAttempts: attempt + 1,
        generationError: '',
      },
    });
    console.log(`[auto-verification] paper ${paperId} 生成成功（第 ${attempt + 1} 次尝试）`);
    return result;
  } catch (err) {
    console.warn(`[auto-verification] paper ${paperId} 第 ${attempt + 1} 次失败: ${err.message}`);
    if (attempt + 1 < MAX_RETRY_ATTEMPTS) {
      await db.collection('papers').doc(paperId).update({
        data: { generationAttempts: attempt + 1, generationError: err.message },
      }).catch(() => {});
      await new Promise(r => setTimeout(r, RETRY_DELAY_MS));
      return generateWithRetry(db, cloud, { paperId, studentId, subject, targets, attempt: attempt + 1 });
    }
    // 最终失败
    await db.collection('papers').doc(paperId).update({
      data: {
        generationStatus: 'failed',
        generationAttempts: attempt + 1,
        generationError: err.message,
      },
    }).catch(() => {});
    console.error(`[auto-verification] paper ${paperId} 最终失败: ${err.message}`);
  }
}

/**
 * 主入口：诊断报告完成后触发自动生成验证卷
 *
 * @param {object} cloud - wx-server-sdk cloud 实例
 * @param {object} db - cloud.database() 实例
 * @param {object} params - { reportId, studentId, subject, profile, openId }
 */
async function triggerAutoVerificationPaper(cloud, db, { reportId, studentId, subject, profile, openId }) {
  const targets = extractPendingTargets(profile);
  if (targets.length === 0) {
    console.log('[auto-verification] 无 pendingBottlenecks，跳过');
    return { triggered: false, reason: 'no_pending_bottlenecks' };
  }

  console.log(`[auto-verification] 触发自动生成：student=${studentId}, subject=${subject}, targets=${targets.length}个`);

  // 1. 覆盖旧卷
  const supersededCount = await supersedeOldPapers(db, studentId, subject, reportId);
  if (supersededCount > 0) {
    console.log(`[auto-verification] 覆盖了 ${supersededCount} 份旧验证卷`);
  }

  // 2. 创建 generating 状态记录
  const paperId = await createGeneratingPaper(db, {
    studentId, subject, targets, reportId, openId: openId || '',
  });

  // 3. 带重试的生成
  try {
    await generateWithRetry(db, cloud, { paperId, studentId, subject, targets });
  } catch (err) {
    // generateWithRetry 内部已处理重试和失败标记，这里只兜底
    console.error('[auto-verification] 异常:', err.message);
  }

  return { triggered: true, paperId };
}

module.exports = {
  triggerAutoVerificationPaper,
  extractPendingTargets,
  supersedeOldPapers,
};
