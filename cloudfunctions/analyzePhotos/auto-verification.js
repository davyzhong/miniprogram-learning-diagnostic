/**
 * 验证卷自动生成引擎
 *
 * 诊断报告完成后，如果有 pendingBottlenecks，自动触发验证卷生成。
 * 用户无需手动点击"生成验证卷"，只需下载/打印/上传作答。
 *
 * 设计文档：docs/subject-design/验证卷自动生成设计文档.md
 */

const MAX_RETRY_ATTEMPTS = 3;
const RETRY_DELAY_MS = 10000; // 10秒后重试

// 分批生成：真实数据下 2-8 个卡点一批仍可能触发 60s 调用超时。
// 默认每批只推进 1 个细 BN，靠续跑机制完成整份卷子。
const BATCH_SIZE = 1;

const SEVERITY_RANK = { high: 3, medium: 2, low: 1 };
// 不再限制细卡点数量：验证卷应该覆盖全量细分卡点（BN），
// 由 generatePaper 的分批追加模式处理题量，而不是在这里截断。
const MAX_FINE_BOTTLENECKS = Infinity;

/**
 * 从 profile 展开细卡点（BN-*），按 severity 排序后截取。
 *
 * 改前：优先取粗卡点 lpCode → 每个出 3 题 → 9 题
 * 改后：展开 candidateBottlenecks 为 BN 细卡点 → 每个出 2 题 → 动态题量
 *
 * 返回格式：[{ bottleneckId, title, severity, lpCode（父级粗卡点） }]
 */
function extractFineBottlenecks(profile) {
  // 同时读 pendingBottlenecks 和 currentBottlenecks（后者是 merge 后的全量数据）
  const pending = (profile && profile.pendingBottlenecks) || [];
  const current = (profile && profile.currentBottlenecks) || [];
  // 合并去重（按 lpCode），candidateBottlenecks 合并而非丢弃
  const coarseMap = new Map();
  for (const item of [...pending, ...current]) {
    const key = item.lpCode || item.bottleneckId || item.id;
    if (!key) continue;
    if (!coarseMap.has(key)) {
      coarseMap.set(key, { ...item, candidateBottlenecks: [...(item.candidateBottlenecks || [])] });
    } else {
      // 合并 candidate（去重）
      const existing = coarseMap.get(key);
      const seen = new Set((existing.candidateBottlenecks || []).map(c => c.bottleneckId || c.id));
      for (const cand of (item.candidateBottlenecks || [])) {
        const cid = cand.bottleneckId || cand.id;
        if (cid && !seen.has(cid)) {
          existing.candidateBottlenecks.push(cand);
          seen.add(cid);
        }
      }
    }
  }
  const coarseItems = Array.from(coarseMap.values());

  const fineSeen = new Set();
  const fineList = [];

  for (const item of coarseItems) {
    const parentLpCode = item.lpCode || '';
    const severity = item.severity || 'medium';
    const candidates = item.candidateBottlenecks || [];

    if (candidates.length > 0) {
      // 有细卡点：展开每个 candidateBottleneck
      for (const cand of candidates) {
        const bnId = cand.bottleneckId || cand.id;
        if (!bnId || fineSeen.has(bnId)) continue;
        fineSeen.add(bnId);
        // 从 evidenceStrength 映射 weight，与 generatePaper 的 weightMap 逻辑一致
        const strength = cand.evidenceStrength;
        const weight = cand.weight || item.weight
          || (strength === 'high' ? 85 : strength === 'medium' ? 60 : 30);
        fineList.push({
          bottleneckId: bnId,
          title: cand.title || cand.lpName || '未知卡点',
          severity,
          lpCode: parentLpCode,
          weight,
        });
      }
    } else {
      // 无细卡点：用粗卡点作 fallback（标注 coarse）
      const code = parentLpCode || item.bottleneckId || item.id;
      if (code && !fineSeen.has(code)) {
        fineSeen.add(code);
        fineList.push({
          bottleneckId: code,
          title: item.lpName || '未知卡点',
          severity,
          lpCode: parentLpCode,
          weight: item.weight || 50,
          coarse: true,
        });
      }
    }
  }

  // 按 weight 降序排（置信度高的先出题），stable 保持原始顺序
  fineList.sort((a, b) => (Number(b.weight) || 0) - (Number(a.weight) || 0)
    || (SEVERITY_RANK[b.severity] || 2) - (SEVERITY_RANK[a.severity] || 2)
    || fineList.indexOf(a) - fineList.indexOf(b));
  return fineList.slice(0, MAX_FINE_BOTTLENECKS);
}

// 保留旧函数名兼容（内部调用改为 extractFineBottlenecks）
function extractPendingTargets(profile) {
  return extractFineBottlenecks(profile).map(item => item.bottleneckId);
}

/**
 * 覆盖旧卷：标记同学科未验证的旧验证卷为 superseded
 */
async function supersedeOldPapers(db, studentId, subject, newReportId) {
  const oldPapers = await db.collection('papers')
    .where({
      studentId,
      subject,
      type: 'verification',
    })
    .limit(20)
    .get();

  let superseded = 0;
  for (const old of oldPapers.data || []) {
    // 跳过已 superseded 的
    if (old.generationStatus === 'superseded') continue;
    // 只覆盖没有验证报告的旧卷（即用户还没上传作答的）
    const verifReports = await db.collection('reports')
      .where({ studentId, subject, type: 'verification', paperId: old._id })
      .limit(1)
      .get();
    if ((verifReports.data || []).length === 0) {
      await db.collection('papers').doc(old._id).update({
        data: {
          generationStatus: 'superseded',
          supersededAt: new Date(),
          supersededBy: newReportId,
        },
      });
      superseded += 1;
    }
  }
  return superseded;
}

/**
 * 创建 generating 状态的 paper 记录
 */
async function createGeneratingPaper(db, { studentId, subject, targets, reportId, openId }) {
  const now = new Date();
  const res = await db.collection('papers').add({
    data: {
      _openid: openId,
      studentId,
      subject,
      type: 'verification',
      bottleneckTargets: targets,
      questions: [],
      generationStatus: 'generating',
      verificationStatus: 'pending',   // 新增：验证卷生命周期状态
      autoGenerated: true,
      generationAttempts: 0,
      generationError: '',
      triggeredByReport: reportId,
      createdAt: now,
      generatedAt: now,
    },
  });
  return res._id;
}

/**
 * 调用 generatePaper 云函数生成一批题目（追加到已有 paper）
 * 用 _appendToPaperId 模式：本批题目合并到 paper.questions，不重新生成 PDF。
 */
async function appendBatch({ cloud, paperId, studentId, subject, targets }) {
  const res = await cloud.callFunction({
    name: 'generatePaper',
    data: {
      studentId,
      subject,
      type: 'verification',
      targets,
      _appendToPaperId: paperId,
    },
  });
  const result = res.result || {};
  if (!result.success) {
    throw new Error(result.error || 'generatePaper 追加失败');
  }
  return result;
}

/**
 * 调用 generatePaper 重新生成最终 PDF（所有批次追加完成后）
 * 用 _regeneratePdf 模式：读取 paper 全部题目，重建分页和 PDF。
 */
async function regenerateFinalPdf({ cloud, paperId }) {
  const res = await cloud.callFunction({
    name: 'generatePaper',
    data: {
      _regeneratePdf: true,
      paperId,
    },
  });
  const result = res.result || {};
  if (!result.success) {
    throw new Error(result.error || 'PDF 重新生成失败');
  }
  if (!result.pdfFileId) {
    throw new Error('PDF 文件未生成');
  }
  return result;
}

/**
 * 单次调用带重试
 */
async function callWithRetry(fn, args, attempt = 0) {
  try {
    return await fn(args);
  } catch (err) {
    if (attempt + 1 < MAX_RETRY_ATTEMPTS) {
      await new Promise(r => setTimeout(r, RETRY_DELAY_MS));
      return callWithRetry(fn, args, attempt + 1);
    }
    throw err;
  }
}

/**
 * 将 targets 按 BATCH_SIZE 切分
 */
function chunkTargets(targets, size = BATCH_SIZE) {
  const chunks = [];
  for (let i = 0; i < targets.length; i += size) {
    chunks.push(targets.slice(i, i + size));
  }
  return chunks;
}

function scheduleVerificationContinuation(cloud, { paperId, studentId, subject, reportId = '' }) {
  cloud.callFunction({
    name: 'regenerateVerificationPaper',
    data: {
      action: 'continue',
      paperId,
      studentId,
      subject,
      reportId,
    },
  }).catch(err => {
    console.error('续跑验证卷生成失败：', err);
  });
}

/**
 * 分批追加生成验证卷（规避单次 60s 超时）
 *
 * 流程：
 * 1. 按 weight 降序排 targets，每批 BATCH_SIZE 个
 * 2. 逐批调用 generatePaper(_appendToPaperId)，题目追加到 paper
 * 3. 全部批次完成后，调用 generatePaper(_regeneratePdf) 生成最终 PDF
 * 4. 单批失败独立重试；任一批最终失败则整份验证卷标记 failed
 */
async function generateInBatches(db, cloud, { paperId, studentId, subject, targets, reportId = '' }) {
  const targetIds = targets.map(t => t.bottleneckId || t);
  const batches = chunkTargets(targetIds);
  const totalBatches = batches.length;
  let succeededBatches = 0;
  let totalAppended = 0;
  const failedBatchDetails = [];

  console.log(`[auto-verification] 分批生成：${targetIds.length} 个卡点，分 ${totalBatches} 批`);

  for (let i = 0; i < batches.length; i++) {
    const batchTargets = batches[i];
    try {
      const result = await callWithRetry(appendBatch, { cloud, paperId, studentId, subject, targets: batchTargets });
      succeededBatches += 1;
      totalAppended += Number(result.appendedQuestionCount) || 0;
      console.log(`[auto-verification] 批次 ${i + 1}/${totalBatches} 完成，追加 ${result.appendedQuestionCount || 0} 题`);

      // 更新进度（供前端轮询展示）
      await db.collection('papers').doc(paperId).update({
        data: {
          generationStatus: 'appending',
          generationProgress: { completedBatches: i + 1, totalBatches, succeededBatches },
        },
      }).catch(() => {});
    } catch (err) {
      console.warn(`[auto-verification] 批次 ${i + 1}/${totalBatches} 最终失败: ${err.message}`);
      failedBatchDetails.push({
        batchIndex: i + 1,
        targets: batchTargets,
        error: err.message || String(err),
      });
      await db.collection('papers').doc(paperId).update({
        data: {
          generationStatus: 'appending',
          generationProgress: {
            completedBatches: i + 1,
            totalBatches,
            succeededBatches,
            failedBatches: failedBatchDetails.length,
            failedBatchIndexes: failedBatchDetails.map(item => item.batchIndex),
          },
        },
      }).catch(() => {});
    }
  }

  if (failedBatchDetails.length > 0) {
    const message = succeededBatches === 0
      ? `全部 ${totalBatches} 批次生成均失败`
      : `部分批次生成失败：${failedBatchDetails.length}/${totalBatches}`;
    await db.collection('papers').doc(paperId).update({
      data: {
        generationStatus: 'failed',
        generationError: message,
        generationProgress: {
          completedBatches: succeededBatches,
          totalBatches,
          succeededBatches,
          failedBatches: failedBatchDetails.length,
          failedBatchIndexes: failedBatchDetails.map(item => item.batchIndex),
          failedBatchDetails,
        },
      },
    }).catch(() => {});
    if (reportId) {
      await db.collection('reports').doc(reportId).update({
        data: { verificationPaperStatus: 'failed' },
      }).catch(() => {});
    }
    throw new Error(message);
  }

  // 全部批次成功后，重新生成最终 PDF
  console.log(`[auto-verification] 批次完成 ${succeededBatches}/${totalBatches}，开始生成最终 PDF`);
  let pdfResult;
  try {
    pdfResult = await callWithRetry(regenerateFinalPdf, { cloud, paperId });
  } catch (err) {
    const message = err.message || String(err);
    await db.collection('papers').doc(paperId).update({
      data: {
        generationStatus: 'failed',
        generationError: message,
        generationProgress: { completedBatches: totalBatches, totalBatches, succeededBatches },
      },
    }).catch(() => {});
    if (reportId) {
      await db.collection('reports').doc(reportId).update({
        data: { verificationPaperStatus: 'failed' },
      }).catch(() => {});
    }
    throw err;
  }

  await db.collection('papers').doc(paperId).update({
    data: {
      generationStatus: 'ready',
      generationError: '',
      generationProgress: { completedBatches: totalBatches, totalBatches, succeededBatches },
    },
  });
  if (reportId) {
    await db.collection('reports').doc(reportId).update({
      data: { verificationPaperStatus: 'ready' },
    }).catch(() => {});
  }

  console.log(`[auto-verification] paper ${paperId} 生成成功：共 ${pdfResult.questionCount || totalAppended} 题`);
  return pdfResult;
}

/**
 * 主入口：诊断报告完成后触发自动生成验证卷
 *
 * @param {object} cloud - wx-server-sdk cloud 实例
 * @param {object} db - cloud.database() 实例
 * @param {object} params - { reportId, studentId, subject, profile, openId }
 */
async function triggerAutoVerificationPaper(cloud, db, { reportId, studentId, subject, profile, openId }) {
  const fineBottlenecks = extractFineBottlenecks(profile);
  const targetIds = fineBottlenecks.map(item => item.bottleneckId);
  if (targetIds.length === 0) {
    console.log('[auto-verification] 无 pendingBottlenecks，跳过');
    return { triggered: false, reason: 'no_pending_bottlenecks' };
  }

  console.log(`[auto-verification] 触发自动生成：student=${studentId}, subject=${subject}, targets=${targetIds.length}个`);

  // 1. 覆盖旧卷
  const supersededCount = await supersedeOldPapers(db, studentId, subject, reportId);
  if (supersededCount > 0) {
    console.log(`[auto-verification] 覆盖了 ${supersededCount} 份旧验证卷`);
  }

  // 2. 创建 generating 状态记录（含批次信息，供前端和报告页展示进度）
  const batches = chunkTargets(targetIds);
  const paperId = await createGeneratingPaper(db, {
    studentId, subject, targets: targetIds, reportId, openId: openId || '',
  });

  // 记录分批进度信息。
  await db.collection('papers').doc(paperId).update({
    data: {
      generationStatus: 'generating',
      generationProgress: { completedBatches: 0, totalBatches: batches.length, succeededBatches: 0 },
    },
  }).catch(() => {});

  // 2.1 回写 verificationPaperId 到诊断报告（建立 report→paper 双向关联）
  if (reportId && paperId) {
    try {
      await db.collection('reports').doc(reportId).update({
        data: { verificationPaperId: paperId, verificationPaperStatus: 'generating' }
      });
    } catch (e) {
      console.warn('[auto-verification] 回写 verificationPaperId 失败:', e.message);
    }
  }

  // 3. 安排短任务续跑。每次只推进一个卡点，避免 analyzePhotos 被验证卷生成拖到超时。
  scheduleVerificationContinuation(cloud, { paperId, studentId, subject, reportId });
  return {
    triggered: true,
    paperId,
    totalBatches: batches.length,
    status: 'generating',
  };
}

module.exports = {
  triggerAutoVerificationPaper,
  extractFineBottlenecks,
  extractPendingTargets,
  supersedeOldPapers,
  generateInBatches,
  chunkTargets,
  scheduleVerificationContinuation,
};
